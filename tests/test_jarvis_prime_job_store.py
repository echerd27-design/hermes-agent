class TestLoadSave:
    def test_load_roundtrips_caller_fields(self, store: JobStore):
        record = store.create_job({"prompt": "p", "nested": {"a": 1}})
        loaded = store.load_job(record["id"])
        assert loaded["prompt"] == "p"
        assert loaded["nested"] == {"a": 1}
        assert loaded["id"] == record["id"]

    def test_load_missing_raises_filenotfound(self, store: JobStore):
        with pytest.raises(FileNotFoundError):
            store.load_job("nope")

    def test_save_preserves_id_and_created_at(self, store: JobStore):
        record = store.create_job({"prompt": "old"})
        jid = record["id"]
        original_created = record["created_at"]

        saved = store.save_job(jid, {"prompt": "new", "id": "hijack", "created_at": "1999-01-01T00:00:00+00:00"})
        assert saved["id"] == jid
        assert saved["created_at"] == original_created
        assert saved["prompt"] == "new"

        on_disk = store.load_job(jid)
        assert on_disk["id"] == jid
        assert on_disk["created_at"] == original_created
        assert on_disk["prompt"] == "new"

    def test_save_bumps_updated_at(self, store: JobStore):
        import time

        record = store.create_job({"prompt": "p"})
        # Sleep > 1s so the second ISO timestamp (second precision) differs.
        time.sleep(1.1)
        saved = store.save_job(record["id"], {"prompt": "p2"})
        assert saved["updated_at"] >= record["updated_at"]
        assert saved["updated_at"] != record["created_at"]

    def test_save_missing_raises_filenotfound(self, store: JobStore):
        with pytest.raises(FileNotFoundError):
            store.save_job("nope", {"prompt": "x"})

    def test_save_leaves_no_tempfiles(self, store: JobStore):
        record = store.create_job({"prompt": "p"})
        store.save_job(record["id"], {"prompt": "p2"})
        leftover = list(store.job_dir(record["id"]).glob(".job_*.tmp"))
        assert leftover == []


class TestListJobs:
    def test_returns_sorted_ids(self, store: JobStore):
        store.create_job(job_id="c")
        store.create_job(job_id="a")
        store.create_job(job_id="b")
        assert store.list_jobs() == ["a", "b", "c"]

    def test_skips_orphan_dirs_without_job_json(self, store: JobStore):
        store.create_job(job_id="real")
        (store.root / "orphan").mkdir()
        assert store.list_jobs() == ["real"]

    def test_empty_store(self, store: JobStore):
        assert store.list_jobs() == []


class TestDeleteJob:
    def test_removes_directory_tree(self, store: JobStore):
        record = store.create_job({"prompt": "p"})
        jid = record["id"]
        jdir = store.job_dir(jid)
        # Drop a sentinel inside artifacts to ensure recursive removal.
        (jdir / "artifacts" / "x.txt").write_text("data")

        assert store.delete_job(jid) is True
        assert not jdir.exists()

    def test_missing_returns_false(self, store: JobStore):
        assert store.delete_job("nope") is False


