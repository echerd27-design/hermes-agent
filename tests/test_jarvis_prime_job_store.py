class TestDefaultRoot:
    def test_default_root_follows_hermes_home(self, tmp_path: Path, monkeypatch):
        monkeypatch.setenv("HERMES_HOME", str(tmp_path))
        s = JobStore()
        assert s.root == (tmp_path / "jobs").resolve()
        assert s.root.is_dir()

    def test_explicit_root_overrides_env(self, tmp_path: Path, monkeypatch):
        monkeypatch.setenv("HERMES_HOME", str(tmp_path / "ignored"))
        custom = tmp_path / "custom"
        s = JobStore(root=custom)
        assert s.root == custom.resolve()

    def test_default_root_is_resolved_lazily(self, tmp_path: Path, monkeypatch):
        # Construct first, redirect HERMES_HOME after — the redirect must win.
        s = JobStore()
        monkeypatch.setenv("HERMES_HOME", str(tmp_path))
        assert s.root == (tmp_path / "jobs").resolve()


