class TestLedger:
    def test_append_injects_ts_when_absent(self, store: JobStore):
        record = store.create_job({"prompt": "p"})
        written = store.append_ledger(record["id"], {"event": "started"})
        assert "ts" in written
        # Round-trip via disk to make sure the ts landed there too.
        entries = store.read_ledger(record["id"])
        assert len(entries) == 1
        assert entries[0]["event"] == "started"
        assert entries[0]["ts"] == written["ts"]

    def test_append_preserves_caller_ts(self, store: JobStore):
        record = store.create_job()
        caller_ts = "1999-12-31T23:59:59+00:00"
        store.append_ledger(record["id"], {"event": "manual", "ts": caller_ts})
        entries = store.read_ledger(record["id"])
        assert entries[0]["ts"] == caller_ts

    def test_append_is_append_only(self, store: JobStore):
        record = store.create_job()
        for n in range(3):
            store.append_ledger(record["id"], {"event": f"e{n}", "ts": f"t{n}"})
        entries = store.read_ledger(record["id"])
        assert [e["event"] for e in entries] == ["e0", "e1", "e2"]
        # Disk view: exactly three non-empty lines.
        raw = (store.job_dir(record["id"]) / "ledger.jsonl").read_text()
        assert [ln for ln in raw.splitlines() if ln.strip()] == raw.splitlines()
        assert len(raw.splitlines()) == 3

    def test_append_rejects_non_dict(self, store: JobStore):
        record = store.create_job()
        with pytest.raises(TypeError):
            store.append_ledger(record["id"], "not a dict")  # type: ignore[arg-type]

    def test_append_missing_job_raises(self, store: JobStore):
        with pytest.raises(FileNotFoundError):
            store.append_ledger("nope", {"event": "x"})

    def test_read_ledger_returns_empty_when_no_appends(self, store: JobStore):
        record = store.create_job()
        assert store.read_ledger(record["id"]) == []

    def test_read_ledger_skips_malformed_lines(self, store: JobStore, caplog):
        record = store.create_job()
        store.append_ledger(record["id"], {"event": "ok1"})
        # Inject a corrupt line by hand.
        with open(store.job_dir(record["id"]) / "ledger.jsonl", "a", encoding="utf-8") as f:
            f.write("not-json\n")
        store.append_ledger(record["id"], {"event": "ok2"})

        entries = store.read_ledger(record["id"])
        assert [e["event"] for e in entries] == ["ok1", "ok2"]

    def test_read_ledger_missing_file_returns_empty(self, store: JobStore):
        # Read for a job that does not exist — no ledger file, no error.
        assert store.read_ledger("nope") == []


