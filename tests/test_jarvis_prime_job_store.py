"""Tests for hermes_cli.jarvis_prime.job_store.JobStore.

Every test passes an explicit ``root`` so the file is runnable in isolation
outside the hermes-agent conftest. The one ``HERMES_HOME`` default-root test
exercises the lazy ``get_hermes_home()`` integration.
"""

import json
from pathlib import Path

import pytest

from hermes_cli.jarvis_prime.job_store import JobStore


@pytest.fixture()
def store(tmp_path: Path) -> JobStore:
    return JobStore(root=tmp_path / "jobs")


# ---------------------------------------------------------------------------
# Directory layout
# ---------------------------------------------------------------------------


class TestCreateJob:
    def test_builds_directory_shape(self, store: JobStore):
        record = store.create_job({"prompt": "hello"})
        jdir = store.job_dir(record["id"])
        assert jdir.is_dir()
        assert (jdir / "job.json").is_file()
        assert (jdir / "ledger.jsonl").is_file()
        assert (jdir / "ledger.jsonl").read_text() == ""
        assert (jdir / "artifacts").is_dir()
        assert (jdir / "reports").is_dir()

    def test_autogenerated_id_is_12_hex(self, store: JobStore):
        record = store.create_job()
        jid = record["id"]
        assert len(jid) == 12
        assert all(c in "0123456789abcdef" for c in jid)
        assert (store.root / jid).is_dir()

    def test_caller_supplied_id_is_honoured(self, store: JobStore):
        record = store.create_job({"x": 1}, job_id="abc123")
        assert record["id"] == "abc123"
        assert (store.root / "abc123" / "job.json").is_file()

    def test_rejects_duplicate_id(self, store: JobStore):
        store.create_job(job_id="dup")
        with pytest.raises(FileExistsError):
            store.create_job(job_id="dup")

    def test_persists_caller_fields_alongside_bookkeeping(self, store: JobStore):
        record = store.create_job({"prompt": "p", "state": "queued"})
        on_disk = json.loads(store._job_file(record["id"]).read_text())
        assert on_disk["prompt"] == "p"
        assert on_disk["state"] == "queued"
        assert on_disk["id"] == record["id"]
        assert "created_at" in on_disk
        assert on_disk["created_at"] == on_disk["updated_at"]

    def test_data_id_cannot_override_explicit_job_id(self, store: JobStore):
        record = store.create_job({"id": "fake"}, job_id="real")
        assert record["id"] == "real"
        on_disk = json.loads(store._job_file("real").read_text())
        assert on_disk["id"] == "real"


